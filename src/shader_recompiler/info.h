/// PB-1 (shader pre-build): a translation replayed outside the game. What the translator would
/// read from guest memory comes from a stored shader record instead: the flattened user data
/// (the SRT walker's output), the parsed fetch shader and the vertex attribute V#s.
struct ReplayInputs {
    const std::vector<u32>* flat{};
    const void* fetch{};                    // Gcn::FetchShaderData
    const std::vector<std::array<u32, 4>>* attrib_sharps{}; // one V# per fetch attribute
    const void* tess_constants{};           // TessellationDataConstantBuffer
};
inline thread_local const ReplayInputs* t_replay = nullptr;
// Set only while a queued translation owns its auxiliary fetch programs.
inline thread_local const std::vector<Common::FetchCodeSnapshot>* t_fetch_code_snapshots = nullptr;

enum class Qualifier : u8 {
    None,
    Smooth,
    NoPerspective,
    PerVertex,
    Flat,
    Centroid,
    Sample,
};

/**
 * Contains general information generated by the shader recompiler for an input program.
 */
struct InfoPersistent {
    BufferResourceList buffers;
    ImageResourceList images;
    SamplerResourceList samplers;
    FMaskResourceList fmasks;

    u32 fetch_shader_sgpr_base{};
    u32 shared_memory_scratch_size{};

    u64 pgm_hash{};

    s32 tess_consts_dword_offset = -1;
    IR::ScalarReg tess_consts_ptr_base = IR::ScalarReg::Max;
    HwStage hw_stage;
    SwStage sw_stage;

    u8 mrt_mask{};
    bool has_fetch_shader{};
    bool has_bitwise_xor{};
    bool uses_dma{};
    bool uses_direct{}; // D2

    InfoPersistent() = default;
    InfoPersistent(HwStage hw_stage_, SwStage sw_stage_, u64 pgm_hash_)
        : hw_stage{hw_stage_}, sw_stage{sw_stage_}, pgm_hash{pgm_hash_} {}
};

struct Info : InfoPersistent {
    // Parsed while translating; guest fetch code may be reused before async results are harvested.
    std::shared_ptr<const Gcn::FetchShaderData> translated_fetch_shader;

    struct AttributeFlags {
        bool Get(IR::Attribute attrib, u32 comp = 0) const {
            return flags[Index(attrib)] & (1 << comp);
        }

        bool GetAny(IR::Attribute attrib) const {
            return flags[Index(attrib)];
        }

        void Set(IR::Attribute attrib, u32 comp = 0) {
            flags[Index(attrib)] |= (1 << comp);
        }

        u32 NumComponents(IR::Attribute attrib) const {
            return 4;
        }

        static size_t Index(IR::Attribute attrib) {
            return static_cast<size_t>(attrib);
        }

        std::array<u8, IR::NumAttributes> flags;
    };

    enum class ReadConstType {
        None = 0,
        Immediate = 1 << 0,
        Dynamic = 1 << 1,
    };

    struct Interpolation {
        Qualifier primary;
        Qualifier auxiliary;
    };

    /// PERF-047: tells this info apart from a later one at the same address (the GPU recorder
    /// keeps its own copies, found by address). Copies keep it.
    u64 identity{NextIdentity()};
    static u64 NextIdentity() {
        static std::atomic<u64> next{1};
        return next.fetch_add(1, std::memory_order_relaxed);
    }

    std::span<const u32> user_data;
    std::vector<u32> flattened_ud_buf;
    // Guest source address of each flattened dword, or zero for user data and unread slots.
    std::vector<u64> flattened_ud_src;
    PersistentSrtInfo srt_info;
    // Outside the serialized POD: keeps executable walker storage alive across Info copies.
    std::shared_ptr<void> srt_walker_owner;

    AttributeFlags loads{};
    AttributeFlags stores{};
    // False for a shader loaded from a cache entry stored without loads/stores (FIX-012); its
    // flags are recovered when a rect/quad-list helper shader needs them.
    bool attribute_flags_known{true};

    ReadConstType readconst_types{};
    CopyShaderData gs_copy_data;
    u32 uses_patches{};

    VAddr pgm_base;
    bool has_storage_images{};
    bool has_discard{};
    bool has_image_gather{};
    bool has_image_query{};
    bool has_flatbuf{};
    bool uses_buffer_atomic_float_min_max{};
    bool uses_image_atomic_float_min_max{};
    bool uses_lane_id{};
    bool uses_shader_clock{};
    bool uses_group_quad{};
    bool uses_group_shuffle{};
    bool uses_group_ballot{};
    IR::Type shared_types{};
    bool uses_fp16{};
    bool uses_fp64{};
    bool uses_pack_10_11_11{};
    bool uses_unpack_10_11_11{};
    bool uses_buffer_int64_atomics{};
    bool uses_shared_int64_atomics{};
    bool stores_tess_level_outer{};
    bool stores_tess_level_inner{};
    bool translation_failed{};

    // FIX-043: which bound-resource properties translation read, so StageSpecialization keys a
    // permutation only on those. Set by the resource patching pass; false for a shader loaded
    // from storage, whose key keeps every property.
    bool resource_usage_known{};
    // The buffer's V# stride entered an address (indexed, thread-id or swizzled addressing).
    std::bitset<NUM_BUFFERS> buffer_stride_used{};
    // The image's sRGB format decided a forced degamma (a sampler with force_degamma).
    std::bitset<NUM_IMAGES> image_srgb_used{};

    std::array<Interpolation, IR::NumParams> fs_interpolation{};

    Info() = default;
    Info(HwStage stage_, SwStage l_stage_, ShaderParams params)
        : InfoPersistent(stage_, l_stage_, params.hash), pgm_base{params.Base()},
          user_data{params.user_data} {}

    template <typename T>
    inline T ReadUdSharp(u32 sharp_idx) const noexcept {
        return *reinterpret_cast<const T*>(&flattened_ud_buf[sharp_idx]);
    }

    template <typename T>
    T ReadUdReg(u32 ptr_index, u32 dword_offset) const noexcept {
        T data;
        const u32* base = user_data.data();
        if (ptr_index == IR::NumScalarRegs) {
            // PERF-GT7-111 (TEST): a sharp in the user registers is not a guest read; its host
            // address changes from one translation to the next, so it stays out of the read log.
            std::memcpy(&data, base + dword_offset, sizeof(T));
            return data;
        }
        {
            std::memcpy(&base, &user_data[ptr_index], sizeof(base));
            base = reinterpret_cast<const u32*>(VAddr(base) & 0xFFFFFFFFFFFFULL);
        }
        // PERF-063: on the recorder, guest bytes captured at decode are read from the capture.
        Common::CopyGuest(&data, base + dword_offset, sizeof(T));
        return data;
    }

    /// FIX-GT7-054: a translation on a worker reads its vertex attributes' V#s here: as the draw
    /// had them, whenever translation, SPIR-V emission and the key get to them. Empty otherwise.
    struct PinnedFetchSharp {
        u32 sgpr_base;
        u32 dword_offset;
        AmdGpu::Buffer sharp;
    };
    std::vector<PinnedFetchSharp> pinned_fetch_sharps;
    bool pin_fetch_sharps{};

    AmdGpu::Buffer ReadFetchSharp(u32 sgpr_base, u32 dword_offset) const noexcept {
        for (const auto& pinned : pinned_fetch_sharps) {
            if (pinned.sgpr_base == sgpr_base && pinned.dword_offset == dword_offset) {
                return pinned.sharp;
            }
        }
        return ReadUdReg<AmdGpu::Buffer>(sgpr_base, dword_offset);
    }

    /// FIX-GT7-124: a translation on a worker reads its tessellation constants here: as its draw
    /// had them, whenever translation and its key get to them. GT7 writes that memory again for
    /// later draws, and since hull shader draws no longer wait for their translation
    /// (PERF-GT7-114/115) the game is frames further when a worker reads it.
    struct PinnedTessConstants {
        u32 ptr_base{};
        s32 dword_offset{-1};
        VAddr sharp_address{}; ///< where the V# was read; 0: from the user data registers
        AmdGpu::Buffer sharp{};
        TessellationDataConstantBuffer constants{};
    };
    std::optional<PinnedTessConstants> pinned_tess_constants;
    /// FIX-GT7-124: set on a worker translating a program whose constants it can't pin yet:
    /// constants that don't fit the draw (SwTessControlRuntimeInfo::FitsConstants,
    /// SwTessEvalRuntimeInfo::FitsConstants) end the translation, with tess_constants_stale set,
    /// instead of being translated.
    bool check_tess_constants{};
    bool tess_constants_stale{};
    /// FIX-GT7-124: the V# and constants the translation was made from, where it read them: its
    /// key, and the manifest's record of its reads, are made from these.
    std::optional<PinnedTessConstants> tess_constants_used;

    /// FIX-GT7-124: the tessellation constants V# at `dword_offset` of the table `ptr_base` points
    /// at (or of the user data registers), and its buffer, as guest memory holds them now.
    static std::optional<PinnedTessConstants> ReadTessConstants(std::span<const u32> user_data,
                                                                u32 ptr_base, s32 dword_offset) {
        if (dword_offset < 0) {
            return std::nullopt;
        }
        PinnedTessConstants pin{.ptr_base = ptr_base, .dword_offset = dword_offset};
        if (ptr_base == IR::NumScalarRegs) {
            if (u64(dword_offset) * 4 + sizeof(pin.sharp) > user_data.size_bytes()) {
                return std::nullopt;
            }
            std::memcpy(&pin.sharp, user_data.data() + dword_offset, sizeof(pin.sharp));
        } else {
            if (u64(ptr_base) + 2 > user_data.size()) {
                return std::nullopt;
            }
            u64 table;
            std::memcpy(&table, &user_data[ptr_base], sizeof(table));
            table &= 0xFFFFFFFFFFFFULL;
            if (table == 0) {
                return std::nullopt;
            }
            // As ReadUdReg reads it.
            pin.sharp_address = table + u64(dword_offset) * sizeof(u32);
            Common::CopyGuest(&pin.sharp, reinterpret_cast<const void*>(pin.sharp_address),
                              sizeof(pin.sharp));
        }
        const VAddr address = pin.sharp.base_address;
        if (address == 0) {
            return std::nullopt;
        }
        Common::CopyGuest(&pin.constants, reinterpret_cast<const void*>(address),
                          sizeof(pin.constants));
        return pin;
    }

    void AddBindings(Backend::Bindings& bnd) const {
        bnd.buffer += buffers.size();
        bnd.unified += buffers.size() + samplers.size();
        for (const auto& image : images) {
            bnd.unified += image.NumBindings(*this);
        }
    }

    void RefreshFlatBuf() {
        if (t_replay && t_replay->flat) { // PB-1
            flattened_ud_buf = *t_replay->flat;
            flattened_ud_buf.resize(std::max<size_t>(flattened_ud_buf.size(), srt_info.flattened_bufsize_dw));
            flattened_ud_src.assign(flattened_ud_buf.size(), 0);
            return;
        }
        flattened_ud_buf.resize(srt_info.flattened_bufsize_dw);
        flattened_ud_src.assign(srt_info.flattened_bufsize_dw, 0);
        ASSERT(user_data.size() <= NUM_USER_DATA_REGS);
        std::memcpy(flattened_ud_buf.data(), user_data.data(), user_data.size_bytes());
        // PERF-GT7-111 (TEST): the walker reads guest memory itself: its output is logged, and
        // replayed without the game.
        Common::GuestReadLog* log = Common::t_guest_read_log;
        if (log && log->replay) {
            log->Take(Common::FlatBufReadTag, flattened_ud_buf.data(),
                      flattened_ud_buf.size() * sizeof(u32));
            return;
        }
        if (srt_info.walker_func) {
            const auto walker_lease = srt_walker_owner;
            srt_info.walker_func(user_data.data(), flattened_ud_buf.data(),
                                 flattened_ud_src.data());
        }
        if (log) {
            log->Append(Common::FlatBufReadTag, flattened_ud_buf.data(),
                        flattened_ud_buf.size() * sizeof(u32));
        }
    }

    /// The tessellation constants V# and buffer at tess_consts_ptr_base/dword_offset, with where
    /// the V# was read: the pinned ones when they are for that V# (FIX-GT7-124), else from guest
    /// memory.
    PinnedTessConstants ReadTessConstantsAt() const {
        ASSERT(tess_consts_dword_offset >= 0); // We've already tracked the V# UD
        const u32 ptr_base = static_cast<u32>(tess_consts_ptr_base);
        if (const auto& pin = pinned_tess_constants;
            pin && pin->ptr_base == ptr_base && pin->dword_offset == tess_consts_dword_offset) {
            // FIX-GT7-124. PERF-GT7-111: a recorded translation logs the reads it stands for, so
            // the manifest replays them in the same order.
            if (Common::GuestReadLog* log = Common::t_guest_read_log; log && !log->replay) {
                if (pin->sharp_address != 0) {
                    log->Append(pin->sharp_address, &pin->sharp, sizeof(pin->sharp));
                }
                log->Append(VAddr(pin->sharp.base_address), &pin->constants,
                            sizeof(pin->constants));
            }
            return *pin;
        }
        PinnedTessConstants read{.ptr_base = ptr_base, .dword_offset = tess_consts_dword_offset};
        if (ptr_base != IR::NumScalarRegs) {
            // Where ReadUdReg reads it.
            u64 table;
            std::memcpy(&table, &user_data[ptr_base], sizeof(table));
            read.sharp_address =
                (table & 0xFFFFFFFFFFFFULL) + u64(tess_consts_dword_offset) * sizeof(u32);
        }
        read.sharp =
            ReadUdReg<AmdGpu::Buffer>(ptr_base, static_cast<u32>(tess_consts_dword_offset));
        VAddr tess_constants_addr = read.sharp.base_address;
        Common::CopyGuest(&read.constants,
                          reinterpret_cast<TessellationDataConstantBuffer*>(tess_constants_addr),
                          sizeof(read.constants));
        return read;
    }

    void ReadTessConstantBuffer(TessellationDataConstantBuffer& tess_constants) const {
        if (t_replay && t_replay->tess_constants) { // PB-1: from the stored runtime info
            std::memcpy(&tess_constants, t_replay->tess_constants, sizeof(tess_constants));
            return;
        }
        tess_constants = ReadTessConstantsAt().constants;
    }

    void Serialize(Serialization::Archive& ar) const;
    bool Deserialize(Serialization::Archive& ar, u64 walker_key = 0,
                     bool has_attribute_flags = true);
};
